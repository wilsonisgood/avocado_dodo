// Figma variables -> src/styles/tokens.css (CSS custom properties, lightMode / darkMode).
import fs from 'node:fs';
import path from 'node:path';
import { loadDoc, localVariables, cssVarName, colorToCss, gid, root } from './lib.mjs';

const { byId } = loadDoc();
const vars = localVariables(byId);
const sets = [...byId.values()].filter((n) => n.type === 'VARIABLE_SET' && !n.key);
const modeName = new Map();
for (const s of sets) for (const m of s.variableSetModes ?? []) modeName.set(gid(m.id), m.name);

const light = [];
const dark = [];
const value = (data) => {
  const v = data.value;
  if (v.alias?.guid) return `var(${cssVarName(vars.get(gid(v.alias.guid)).name)})`;
  if (v.colorValue) return colorToCss(v.colorValue);
  if (v.floatValue != null) return `${v.floatValue}px`;
  return null;
};

const sorted = [...vars.values()].sort((a, b) => a.name.localeCompare(b.name));
for (const v of sorted) {
  for (const e of v.variableDataValues?.entries ?? []) {
    const css = value(e.variableData);
    if (css == null) continue;
    const line = `  ${cssVarName(v.name)}: ${css};`;
    (modeName.get(gid(e.modeID)) === 'darkMode' ? dark : light).push(line);
  }
}

const out = `/* Generated by tools/fig/tokens.mjs from the Figma variables. Do not edit by hand. */
:root {
${light.join('\n')}
}

/* Nestly · Primitives darkMode. Semantic color/* tokens alias the palette, so they follow automatically. */
:root[data-theme='dark'] {
${dark.join('\n')}
}
`;
fs.writeFileSync(path.join(root, 'src/styles/tokens.css'), out);

// ---- Tailwind theme: utilities that point at the variables above --------------------------------
// color/text/primary -> --color-text-primary -> `text-text-primary`, `bg-bg-surface`, `border-border-default`
const theme = [];
for (const v of sorted) {
  const m = /^color\/(.+)$/.exec(v.name);
  if (m) theme.push(`  --color-${m[1].replace(/\//g, '-')}: var(${cssVarName(v.name)});`);
  const r = /^radius\/(\d+)$/.exec(v.name);
  if (r) theme.push(`  --radius-${r[1]}: var(${cssVarName(v.name)});`);
}
const effectStyles = [...byId.values()].filter((n) => n.styleType === 'EFFECT');
for (const e of effectStyles) {
  const shadows = (e.effects ?? []).filter((x) => x.visible !== false && x.type.endsWith('SHADOW')).map((x) =>
    `${x.type === 'INNER_SHADOW' ? 'inset ' : ''}${x.offset.x}px ${x.offset.y}px ${x.radius}px ${x.spread ?? 0}px ${colorToCss(x.color)}`);
  if (shadows.length) theme.push(`  --shadow-${e.name.split('/').pop().toLowerCase()}: ${shadows.join(', ')};`);
}
// Text styles -> `@utility type-heading-large` etc. (font + size + line height + weight)
const weights = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700 };
const utilities = [...byId.values()]
  .filter((n) => n.styleType === 'TEXT')
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((t) => {
    const name = t.name.replace(/^Nestly\//, '').replace(/[\/\s]+/g, '-').toLowerCase();
    const lh = t.lineHeight?.units === 'PIXELS' ? `${t.lineHeight.value}px` : 'normal';
    return `/* ${t.name} */\n@utility type-${name} {\n  font-family: '${t.fontName.family}', sans-serif;\n  font-size: ${t.fontSize}px;\n  line-height: ${lh};\n  font-weight: ${weights[t.fontName.style] ?? 400};\n}`;
  });
fs.writeFileSync(
  path.join(root, 'src/styles/theme.css'),
  `/* Generated by tools/fig/tokens.mjs. Do not edit by hand. */\n@theme inline {\n${theme.join('\n')}\n}\n\n${utilities.join('\n\n')}\n`,
);
console.log(`tokens: ${light.length} light, ${dark.length} dark, ${theme.length} theme entries, ${utilities.length} text styles`);
