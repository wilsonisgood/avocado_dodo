// Export assets from design/.cache:
//   src/components/icons/iconData.ts   Nestly/Icon/* as path data (rendered inline, currentColor when single-color)
//   public/assets/vectors/<id>.svg     every other vector a screen or component uses (charts, blobs, decorations)
//   public/assets/images/<hash>.<ext>  raw images (fruit babies, accessories) + manifest.json
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { loadDoc, gid, colorToCss, root } from './lib.mjs';

const { doc, byId, kids } = loadDoc();
const blob = (i) => Buffer.from(doc.blobs[i], 'base64');

// Figma path blob: [cmd u8][float32 LE...]  0=Z 1=M(x,y) 2=L(x,y) 3=Q(4) 4=C(6)  (PITFALLS §fig 5)
function pathData(i) {
  const b = blob(i);
  const argc = { 1: 2, 2: 2, 3: 4, 4: 6 };
  const letter = { 0: 'Z', 1: 'M', 2: 'L', 3: 'Q', 4: 'C' };
  let o = 0;
  let d = '';
  while (o < b.length) {
    const c = b[o++];
    if (!(c in letter)) throw new Error(`unknown path command ${c} in blob ${i}`);
    const nums = [];
    for (let k = 0; k < (argc[c] ?? 0); k++, o += 4) nums.push(+b.readFloatLE(o).toFixed(3));
    d += letter[c] + nums.join(' ');
  }
  return d;
}

const mul = (a, b) => ({
  m00: a.m00 * b.m00 + a.m01 * b.m10, m01: a.m00 * b.m01 + a.m01 * b.m11, m02: a.m00 * b.m02 + a.m01 * b.m12 + a.m02,
  m10: a.m10 * b.m00 + a.m11 * b.m10, m11: a.m10 * b.m01 + a.m11 * b.m11, m12: a.m10 * b.m02 + a.m11 * b.m12 + a.m12,
});
const ID = { m00: 1, m01: 0, m02: 0, m10: 0, m11: 1, m12: 0 };
const svgMatrix = (t) =>
  [t.m00, t.m10, t.m01, t.m11, t.m02, t.m12].every((x, k) => Math.abs(x - [1, 0, 0, 1, 0, 0][k]) < 1e-4)
    ? undefined
    : `matrix(${[t.m00, t.m10, t.m01, t.m11, t.m02, t.m12].map((x) => +x.toFixed(4)).join(' ')})`;

const varName = new Map();
for (const n of byId.values()) if (n.type === 'VARIABLE') { varName.set(gid(n.guid), n.name); if (n.key) varName.set(n.key, n.name); }
const solid = (paints) => {
  const p = (paints ?? []).find((x) => x.visible !== false && x.type === 'SOLID');
  if (!p) return null;
  const a = p.colorVar?.value?.alias;
  return { css: colorToCss({ ...p.color, a: (p.color.a ?? 1) * (p.opacity ?? 1) }), variable: varName.get(a?.guid ? gid(a.guid) : a?.assetRef?.key) };
};

// Collect drawable paths under a node, in the node's own coordinate space.
function collect(n, t, out, isRoot = true, group = { i: -1 }) {
  if (n.visible === false) return out;
  const local = isRoot ? ID : mul(t, n.transform ?? ID);
  const own = [
    ...(n.fillGeometry ?? []).map((g) => ({ g, paint: solid(n.fillPaints) })),
    ...(n.strokeGeometry ?? []).map((g) => ({ g, paint: n.strokeWeight ? solid(n.strokePaints) : null })),
  ];
  const isFrame = ['FRAME', 'SYMBOL', 'INSTANCE'].includes(n.type);
  const vec = own.some((o) => o.paint) && !(isFrame && isRoot) ? ++group.i : group.i;
  for (const { g, paint } of own) {
    if (!paint) continue;
    if (isFrame && isRoot) continue; // icon/vector containers: background fills are not part of the glyph
    out.push({ vec, d: pathData(g.commandsBlob), transform: svgMatrix(local), evenodd: g.windingRule === 'ODD' || undefined, ...paint });
  }
  if (n.type !== 'BOOLEAN_OPERATION') for (const c of kids(gid(n.guid))) collect(c, local, out, false, group);
  return out;
}

// ---- icons -------------------------------------------------------------------------------------
const icons = {};
for (const n of byId.values()) {
  const m = n.type === 'SYMBOL' && /^Nestly\/Icon\/(.+)$/.exec(n.name ?? '');
  if (!m) continue;
  const paths = collect(n, ID, []);
  const colors = new Set(paths.map((p) => p.css));
  icons[m[1]] = {
    w: +n.size.x.toFixed(3),
    h: +n.size.y.toFixed(3),
    // `vec` = index of the source vector layer; instances recolor per layer (e.g. nav icons are two-tone).
    paths: paths.map(({ vec, d, transform, evenodd, css, variable }) => ({
      vec, d, transform, evenodd,
      // Single-color icons follow currentColor so callers can tint them; multi-color keep their tokens.
      color: colors.size <= 1 ? undefined : variable ? `var(--nestly-${variable.replace(/\//g, '-')})` : css,
    })),
  };
}
fs.mkdirSync(path.join(root, 'src/components/icons'), { recursive: true });
fs.writeFileSync(
  path.join(root, 'src/components/icons/iconData.ts'),
  `// Generated by tools/fig/assets.mjs from Nestly/Icon/* in the .fig. Do not edit by hand.\n` +
    `export type IconPath = { vec: number; d: string; transform?: string; evenodd?: boolean; color?: string };\n` +
    `export const iconData = ${JSON.stringify(icons, null, 1)} satisfies Record<string, { w: number; h: number; paths: IconPath[] }>;\n` +
    `export type IconName = keyof typeof iconData;\n`,
);

// ---- standalone vectors referenced by specs ------------------------------------------------------
const vecIds = JSON.parse(fs.readFileSync(path.join(root, 'design/.cache/vector-nodes.json'), 'utf8'));
const vecDir = path.join(root, 'public/assets/vectors');
fs.rmSync(vecDir, { recursive: true, force: true });
fs.mkdirSync(vecDir, { recursive: true });
let empty = 0;
for (const id of vecIds) {
  const n = byId.get(id);
  const paths = collect(n, ID, []);
  if (!paths.length) empty++;
  const w = +n.size.x.toFixed(3);
  const h = +n.size.y.toFixed(3);
  // Strokes are outlined geometry and may overflow the box; give the viewBox a little slack.
  const pad = Math.max(n.strokeWeight ?? 0, 0);
  const body = paths
    .map((p) => `<path d="${p.d}" fill="${p.css}"${p.transform ? ` transform="${p.transform}"` : ''}${p.evenodd ? ' fill-rule="evenodd"' : ''}/>`)
    .join('');
  fs.writeFileSync(
    path.join(vecDir, `${id.replace(':', '-')}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${-pad} ${-pad} ${w + 2 * pad} ${h + 2 * pad}" overflow="visible">${body}</svg>`,
  );
}

// ---- accessories (Nestly/Accessory/*: 96×64 head pieces, composed into one SVG each) ---------------
const accDir = path.join(root, 'public/assets/accessories');
fs.rmSync(accDir, { recursive: true, force: true });
fs.mkdirSync(accDir, { recursive: true });
const accessories = [];
for (const n of byId.values()) {
  const m = n.type === 'SYMBOL' && /^Nestly\/Accessory\/(\w+)$/.exec(n.name ?? '');
  if (!m) continue;
  const paths = collect(n, ID, []);
  const body = paths.map((p) => `<path d="${p.d}" fill="${p.css}"${p.transform ? ` transform="${p.transform}"` : ''}${p.evenodd ? ' fill-rule="evenodd"' : ''}/>`).join('');
  fs.writeFileSync(path.join(accDir, `${m[1].toLowerCase()}.svg`), `<svg xmlns="http://www.w3.org/2000/svg" width="${n.size.x}" height="${n.size.y}" viewBox="0 0 ${n.size.x} ${n.size.y}" overflow="visible">${body}</svg>`);
  accessories.push(m[1].toLowerCase());
}

// ---- images ------------------------------------------------------------------------------------
const imgDir = path.join(root, 'public/assets/images');
fs.rmSync(imgDir, { recursive: true, force: true });
fs.mkdirSync(imgDir, { recursive: true });
const usedBy = {};
for (const n of byId.values())
  for (const p of n.fillPaints ?? [])
    if (p.type === 'IMAGE' && p.image?.hash) {
      const h = Buffer.from(p.image.hash.bytesBase64, 'base64').toString('hex');
      (usedBy[h] ??= new Set()).add(n.name);
    }
const manifest = {};
for (const f of fs.readdirSync(path.join(root, 'design/.cache/images'))) {
  const src = path.join(root, 'design/.cache/images', f);
  const head = fs.readFileSync(src).subarray(0, 4).toString('hex');
  const ext = head.startsWith('89504e47') ? 'png' : head.startsWith('ffd8') ? 'jpg' : head.startsWith('52494646') ? 'webp' : 'bin';
  if (!usedBy[f]) continue; // not referenced by any node (thumbnails, old versions)
  const dest = path.join(imgDir, `${f}.${ext}`);
  fs.copyFileSync(src, dest);
  // Illustrations are ~1.2MB at 1000px+ but render at <= 180px; 480px keeps 2x+ sharpness (LEDGER D-imgsize).
  execFileSync('sips', ['-Z', '480', dest], { stdio: 'ignore' });
  manifest[f] = { file: `assets/images/${f}.${ext}`, usedBy: [...(usedBy[f] ?? [])].slice(0, 6) };
}
fs.writeFileSync(path.join(imgDir, 'manifest.json'), JSON.stringify(manifest, null, 1));

// Fruit-baby illustrations are named "<week>w <n>" in the design; expose them by pregnancy week.
const fruit = {};
for (const m of Object.values(manifest))
  for (const name of m.usedBy) {
    const w = /^(\d+)w \d+$/.exec(name);
    if (w) fruit[+w[1]] = m.file;
  }
fs.writeFileSync(
  path.join(root, 'src/data/fruitImages.ts'),
  `// Generated by tools/fig/assets.mjs. Pregnancy week -> fruit-baby illustration (public/ path).\n` +
    `export const fruitImages: Record<number, string> = ${JSON.stringify(fruit, null, 1)};\n`,
);
console.log(`assets: ${accessories.length} accessories (${accessories}), ${Object.keys(icons).length} icons, ${vecIds.length} vectors (${empty} empty), ${Object.keys(manifest).length} images`);
